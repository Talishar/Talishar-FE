// Parallel version of card-generator.js that sources card names from the public card data CSV instead of
// the-fab-cube JSON, for when the CSV is more up to date. The CSV has one row per printing (in every
// language), with the front and back of double-faced cards as face_1 and face_2 of the same row.
const axios = require('axios');
const fs = require('fs');

const url = "https://d1pn9y8e99aays.cloudfront.net/public_card_data.csv";

const outputFile = './src/constants/cardList.ts';

// Fixes for mistakes in the CSV's names, using the-fab-cube's names. Keep in sync with the
// $cardCorrections names in Talishar's zzCardCodeGeneratorCSV.php.
const nameCorrections = {
  "Assassin Weapon - Dagger (1H)": "Humour Plunge",
  "Ezy Sqeez Bookie Syndicate": "Ez Sqeez Bookie Syndicate",
  "Knife through Butter": "Knife Through Butter",
  "Tremor of íArathael": "Tremor of i'Arathael",
};

// Parses CSV text into rows of fields, handling quoted fields that contain commas, quotes or newlines
function parseCSV(text) {
  const rows = [];
  let row = [];
  let field = '';
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    if (inQuotes) {
      if (char === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (char === '"') {
        inQuotes = false;
      } else {
        field += char;
      }
    } else if (char === '"') {
      inQuotes = true;
    } else if (char === ',') {
      row.push(field);
      field = '';
    } else if (char === '\n' || char === '\r') {
      if (char === '\r' && text[i + 1] === '\n') i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else {
      field += char;
    }
  }
  if (field !== '' || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

axios
  .get(url, { responseType: 'text' })
  .then((response) => {
    const [header, ...rows] = parseCSV(response.data);
    const column = (name) => header.indexOf(name);
    const languageColumn = column('print_language');
    const nameColumns = [column('face_1_true_name'), column('face_2_true_name')];

    const printings = rows.filter((row) => row[languageColumn] === 'en');
    console.log(`Total printings fetched: ${printings.length}`);

    const cardNames = new Set();
    for (const row of printings) {
      for (const nameColumn of nameColumns) {
        let name = row[nameColumn].trim();
        if (name === '') continue;
        name = nameCorrections[name] ?? name;
        // split cards are named "Front||Back"
        for (const part of name.split('||')) {
          cardNames.add(part.trim());
        }
      }
    }

    const sortedCardNames = [...cardNames].sort();

    console.log(`Unique cards found: ${sortedCardNames.length}`);

    const exportData = `// This file is generated by the card-generator script. Do not edit it manually. \nexport const CARD_LIST: string[] = ${JSON.stringify(
      sortedCardNames,
      null,
      2
    )};`;

    fs.mkdirSync('../src/constants', { recursive: true }); // create the constants directory if it doesn't exist
    fs.writeFileSync(outputFile, exportData);
    console.log(`Card list written to ${outputFile}`);
  })
  .catch((err) => {
    console.error('Error fetching or processing cards:');
    console.error(err.message);
    if (err.response) {
      console.error(`Status: ${err.response.status}`);
      console.error(`Data: ${err.response.data}`);
    }
  });
